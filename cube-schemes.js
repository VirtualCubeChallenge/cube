/* ============================================================
   cube-schemes.js — ショップ「キューブカラー」の追加配色（5種）
   ------------------------------------------------------------
   cube-feel.js / ui-polish.js / photo-skin.js と同じ方針で、
   機能ごとに1ファイル。index.html への追記は2行だけ（下記）、
   style.css と i18n.js は無改変。読み込みをやめれば品揃えが
   元の「標準 / エレクトリック」だけに戻る。

   ------------------------------------------------------------
   【導入手順】index.html に足すのはこの2つだけ
   ------------------------------------------------------------
   ① i18n.js の <script> の直後（= <head> の中）に1行:

        <script src="cube-schemes.js?v=20260826c"></script>

      ここに置く理由: Shop の const SCHEMES より "先" に
      window.CUBE_SCHEMES_EXTRA を用意しておく必要がある。
      Shop.init() の loadState() は「SCHEMES に無いidは持ち物から
      落とす」作りなので、後読みにすると買った配色が次回起動で
      消えてしまう。

   ② index.html の Shop 内、const SCHEMES = [ ... ]; の閉じ括弧の
      直後に1行:

        if (Array.isArray(window.CUBE_SCHEMES_EXTRA)) SCHEMES.push.apply(SCHEMES, window.CUBE_SCHEMES_EXTRA);

      （元の SCHEMES の中身は触らない。標準・エレクトリックの
        後ろに5枠が並ぶ）

   ③ 名前は i18n.js（SCHEME_I18N）に9言語ぶん入れてある。
   ④ いつもどおり index.html の ?v= と sw.js の SW_BUILD_MARKER を上げる。

   ------------------------------------------------------------
   【色の決め方】
   - colors … 3D本体のステッカー色（I = 面と面のあいだ＝内側の色）
   - bg     … scene.background
   - gapSize… マスの一辺（基準 CUBIE_BASE_SIZE = 0.94）。
              背景が暗い配色ほど、すき間から覗く色が「黒い線」に
              見えるので詰める。明るい背景の配色は、すき間が
              そのまま「白いキューブ本体」に見えるので詰めない。
   - faceColors … 回転記号ボタン／持ち替え中の色判定が見る文字列hex。
              これを渡さないと本体だけ色が変わってボタンが標準色の
              まま残る。text は bg の明るさに合わせて白/黒を選ぶ。

   赤と橙は、どの配色でも色相を30度前後は離してある（標準色の
   #B71234 と #FF5800 と同じくらいの間隔）。ここが近いと、揃った
   かどうかの判定が目視でできなくなる。
   ============================================================ */
(function (global) {
  'use strict';

  if (global.CUBE_SCHEMES_EXTRA) return;   // 二重読み込みよけ

  /* ============================================================
     ① 和（わ）— 日本の伝統色。藍は寿司屋の暖簾と同じ #1f6f9c。
        背景は墨に近い温かい黒。
     ============================================================ */
  const WA = {
    id: 'wa', cost: 500, cur: 'cyan',
    colors: {
      R: 0xC8102E,   // 朱
      L: 0xEF7A34,   // 柿
      U: 0xF4EDE0,   // 生成り
      D: 0xE8A400,   // 山吹
      F: 0x2E9E6B,   // 若竹
      B: 0x1F6F9C,   // 藍
      I: 0x2A2620
    },
    bg: 0x17140F,
    gapSize: 0.97,
    faceColors: {
      R: { bg: '#C8102E', text: '#ffffff' },
      L: { bg: '#EF7A34', text: '#141416' },
      U: { bg: '#F4EDE0', text: '#141416' },
      D: { bg: '#E8A400', text: '#141416' },
      F: { bg: '#2E9E6B', text: '#ffffff' },
      B: { bg: '#1F6F9C', text: '#ffffff' }
    }
  };

  /* ============================================================
     ② パステル — 黒地に淡色。赤をピンク寄りにして橙と分けてある。
        淡い色は明るい背景だと沈むので、背景を黒にして浮かせる。
        内側は濃いグレーにして、すき間を細い暗線として見せる。
     ============================================================ */
  const PASTEL = {
    id: 'pastel', cost: 500, cur: 'cyan',
    colors: {
      R: 0xF98BB0,
      L: 0xFFB27A,
      U: 0xFDFDFF,
      D: 0xFFDF7E,
      F: 0x86DCA6,
      B: 0x9CC4FF,
      I: 0x2A2A31
    },
    bg: 0x000000,
    gapSize: 0.97,
    faceColors: {
      R: { bg: '#F98BB0', text: '#141416' },
      L: { bg: '#FFB27A', text: '#141416' },
      U: { bg: '#FDFDFF', text: '#141416' },
      D: { bg: '#FFDF7E', text: '#141416' },
      F: { bg: '#86DCA6', text: '#141416' },
      B: { bg: '#9CC4FF', text: '#141416' }
    }
  };

  /* ============================================================
     ③ ジュエル — 宝石の名前で選んだ深い彩度。エレクトリックの
        「派手」に対して「重厚」。背景はほぼ黒（青に寄せてある）。
     ============================================================ */
  const JEWEL = {
    id: 'jewel', cost: 500, cur: 'cyan',
    colors: {
      R: 0xA8123C,   // ルビー
      L: 0xD96C13,   // アンバー
      U: 0xE8EEF2,   // パール
      D: 0xE8A31E,   // シトリン
      F: 0x0FA36B,   // エメラルド
      B: 0x1B3FA0,   // サファイア
      I: 0x0E0E16
    },
    bg: 0x08080F,
    gapSize: 0.995,
    faceColors: {
      R: { bg: '#A8123C', text: '#ffffff' },
      L: { bg: '#D96C13', text: '#141416' },
      U: { bg: '#E8EEF2', text: '#141416' },
      D: { bg: '#E8A31E', text: '#141416' },
      F: { bg: '#0FA36B', text: '#ffffff' },
      B: { bg: '#1B3FA0', text: '#ffffff' }
    }
  };

  /* ============================================================
     ④ ネオンポップ — 蛍光色に振った明るい配色。並びは Okabe-Ito の
        カラーユニバーサル推奨色そのままなので、見た目が派手なだけで
        なく、赤と緑の見分けが苦手な人でも6面を判別できる。要点は
        「橙をピンクに置き換える」こと。
     ============================================================ */
  const NEON_POP = {
    id: 'neonPop', cost: 500, cur: 'cyan',
    colors: {
      R: 0xD55E00,   // 朱（vermillion）
      L: 0xE86FB4,   // ピンク（橙の代わり）
      U: 0xFFFFFF,
      D: 0xF5E14C,
      F: 0x009E73,
      B: 0x0072B2,
      I: 0x2A2A30
    },
    bg: 0x121214,    // 標準と同じ背景
    // 標準寸法(未指定=0.94)のままだと、蛍光色の隣に来る黒い線が
    // 太く目立ちすぎた。ジュエルと同じ 0.995 まで詰めて細い線にする。
    gapSize: 0.995,
    faceColors: {
      R: { bg: '#D55E00', text: '#141416' },
      L: { bg: '#E86FB4', text: '#141416' },
      U: { bg: '#FFFFFF', text: '#141416' },
      D: { bg: '#F5E14C', text: '#141416' },
      F: { bg: '#009E73', text: '#ffffff' },
      B: { bg: '#0072B2', text: '#ffffff' }
    }
  };

  /* ============================================================
     ⑤ モノクローム — 色相をぜんぶ捨て、明度差だけで解く上級者向け。
        6段の明るさは等間隔に振ってあるので、色覚に関係なく
        「並び順」で判別できる。背景は明るいグレー。
     ============================================================ */
  const MONO = {
    id: 'mono', cost: 500, cur: 'cyan',
    colors: {
      U: 0xFFFFFF,
      D: 0xCBD1D8,
      F: 0x969CA5,
      L: 0x5F6570,
      R: 0x383D46,
      B: 0x14171C,
      I: 0xAEB4BC
    },
    bg: 0xE6E9EE,
    faceColors: {
      R: { bg: '#383D46', text: '#ffffff' },
      L: { bg: '#5F6570', text: '#ffffff' },
      U: { bg: '#FFFFFF', text: '#141416' },
      D: { bg: '#CBD1D8', text: '#141416' },
      F: { bg: '#969CA5', text: '#141416' },
      B: { bg: '#14171C', text: '#ffffff' }
    }
  };

  // 並び順 = ショップに出る順。標準・エレクトリックの後ろに続く。
  global.CUBE_SCHEMES_EXTRA = [WA, PASTEL, JEWEL, NEON_POP, MONO];

  /* 文言（各配色の名前）は i18n.js の SCHEME_I18N にまとめてある。
     キーは 'shopScheme' + id の先頭大文字 — wa → shopSchemeWa など。 */
})(window);
